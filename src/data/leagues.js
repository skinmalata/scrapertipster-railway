function detectLeague(teamName) {
  const cleanName = teamName.replace(/[^a-zA-Z]/g, '').toLowerCase();
  
  for (const [team, info] of Object.entries(leagueMap)) {
    const cleanTeam = team.replace(/[^a-zA-Z]/g, '').toLowerCase();
    if (cleanName.includes(cleanTeam) || cleanTeam.includes(cleanName) || teamName.includes(team) || team.includes(teamName)) {
      return info;
    }
  }
  return { league: '', country: '' };
}

function normalizeTeamName(name) {
  return name.toLowerCase()
    .replace(/[^a-z0-9]/g, '')
    .replace(/ç/g, 'c')
    .replace(/ğ/g, 'g')
    .replace(/ı/g, 'i')
    .replace(/ş/g, 's')
    .replace(/ü/g, 'u')
    .replace(/ö/g, 'o')
    .replace(/é/g, 'e')
    .replace(/è/g, 'e')
    .replace(/ê/g, 'e')
    .replace(/à/g, 'a')
    .replace(/â/g, 'a')
    .replace(/á/g, 'a')
    .replace(/ã/g, 'a')
    .replace(/í/g, 'i')
    .replace(/ó/g, 'o')
    .replace(/õ/g, 'o')
    .replace(/ú/g, 'u')
    .replace(/ñ/g, 'n')
    .replace(/ß/g, 'ss')
    .replace(/ø/g, 'o')
    .replace(/æ/g, 'ae')
    .trim();
}

